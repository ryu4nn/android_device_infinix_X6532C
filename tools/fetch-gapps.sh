#!/usr/bin/env bash
#
# fetch-gapps.sh — unpack the pinned Google apps payload into gapps/.
#
#   ./tools/fetch-gapps.sh          # normal use, cached download
#   GAPPS_CACHE=/path ./tools/fetch-gapps.sh
#
# The archive is pinned by URL and sha256 so a build is reproducible. No
# proprietary binary is stored in this repository: the extracted tree and the
# generated gapps.mk and Android.mk are git-ignored, and device.mk only inherits
# gapps.mk when it exists, so a plain `repo sync` tree still builds vanilla
# LineageOS.
#
# MindTheGapps 13 stores its payload under system/product and system/system_ext,
# which are separate partitions on this device, so the three top-level
# directories are mapped to the matching partition roots. Everything else stays
# under /system.

set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
GAPPS="$HERE/gapps"
CACHE="${GAPPS_CACHE:-/tmp/x6532c-gapps}"

NAME="MindTheGapps-13.0.0-arm-20231025_200806.zip"
TAG="MindTheGapps-13.0.0-arm-20231025_200806"
URL="https://github.com/MindTheGapps/13.0.0-arm/releases/download/${TAG}/${NAME}"
SHA256="9f0c3663872488acf98eb3dd548ed53a584f119161192dcd20f904b4cd05a37e"

say() { printf '%s\n' "fetch-gapps: $*"; }

mkdir -p "$CACHE"
ZIP="$CACHE/$NAME"

if [ -f "$ZIP" ] && printf '%s  %s\n' "$SHA256" "$ZIP" | sha256sum -c --status -; then
    say "cached archive verified"
else
    say "downloading $NAME (227 MB)"
    curl -fL --retry 3 --retry-delay 5 -o "$ZIP.part" "$URL"
    printf '%s  %s\n' "$SHA256" "$ZIP.part" | sha256sum -c -
    mv "$ZIP.part" "$ZIP"
fi

TMP="$CACHE/extract"
rm -rf "$TMP"
mkdir -p "$TMP"
unzip -q "$ZIP" -d "$TMP"

# Start from a clean tree so a re-run cannot leave stale files behind.
rm -rf "$GAPPS/system" "$GAPPS/product" "$GAPPS/system_ext" \
       "$GAPPS/gapps.mk" "$GAPPS/Android.mk"
mkdir -p "$GAPPS/system"

for p in system product system_ext; do
    if [ -d "$TMP/system/$p" ]; then
        mv "$TMP/system/$p" "$GAPPS/$p"
    fi
done

# Everything that is not product/ or system_ext/ keeps its /system path.
#
# system/addon.d carries OpenGApps' addond_head/addond_tail fragments. They are
# input to the OpenGApps installer, not standalone backup scripts, and
# LineageOS has its own backuptool in /system/addon.d, so installing these would
# only risk a duplicate PRODUCT_COPY_FILES destination for no function.
tar -C "$TMP/system" -cf - --exclude=./addon.d . | tar -C "$GAPPS/system" -xf -

rm -rf "$TMP"

# ------------------------------------------------------- gapps.mk + Android.mk --
#
# build/make/core/Makefile refuses a prebuilt .apk in PRODUCT_COPY_FILES and
# asks for BUILD_PREBUILT, so every APK becomes a prebuilt module and reaches
# the product through PRODUCT_PACKAGES. Everything else keeps the plain copy
# rule.
#
# The module keeps the archive layout: LOCAL_MODULE_PATH is the partition
# directory the archive uses (product/priv-app and so on), and base_rules.mk
# appends /$(LOCAL_MODULE) for module class APPS, so an app lands in
# <dir>/<Module>/<Module>.apk. Runtime resource overlays are the exception:
# LOCAL_IS_RUNTIME_RESOURCE_OVERLAY suppresses that extra directory, because an
# overlay has to be a bare <Dir>/<Name>.apk.
#
# Names carry an MtG_ prefix so they cannot collide with a module the platform
# already defines.
{
    echo "# Generated by tools/fetch-gapps.sh — do not edit."
    echo "# Archive: $NAME"
    echo "# sha256:  $SHA256"
    echo ""
    echo "LOCAL_PATH := \$(call my-dir)"
    echo ""
} > "$GAPPS/Android.mk"

{
    echo "# Generated by tools/fetch-gapps.sh — do not edit."
    echo "# Archive: $NAME"
    echo "# sha256:  $SHA256"
    echo ""
    echo "GAPPS_DIR ?= \$(LOCAL_PATH)/gapps"
    echo ""
} > "$GAPPS/gapps.mk"

for p in system product system_ext; do
    [ -d "$GAPPS/$p" ] || continue
    case "$p" in
        system)     dst='$(TARGET_COPY_OUT_SYSTEM)';     out='$(TARGET_OUT)' ;;
        product)    dst='$(TARGET_COPY_OUT_PRODUCT)';    out='$(TARGET_OUT_PRODUCT)' ;;
        system_ext) dst='$(TARGET_COPY_OUT_SYSTEM_EXT)'; out='$(TARGET_OUT_SYSTEM_EXT)' ;;
    esac

    find "$GAPPS/$p" -type f -print0 | sort -z | while IFS= read -r -d '' f; do
        rel="${f#"$GAPPS/$p/"}"
        case "$rel" in
            *.apk)
                base="$(basename "$rel" .apk)"
                mod="MtG_$base"
                # The APK usually sits in its own directory
                # (<top>/<Name>/<Name>.apk). base_rules.mk appends
                # /$(LOCAL_MODULE) to LOCAL_MODULE_PATH for module class APPS,
                # which reproduces that directory, so the path must stop at the
                # partition directory (app, priv-app, overlay) and not repeat
                # the name.
                dir="$(dirname "$rel")"
                if [ "$(basename "$dir")" = "$base" ]; then
                    dir="$(dirname "$dir")"
                fi
                [ "$dir" = "." ] && dir=""
                {
                    echo "include \$(CLEAR_VARS)"
                    echo "LOCAL_MODULE := $mod"
                    echo "LOCAL_MODULE_OWNER := google"
                    echo "LOCAL_SRC_FILES := $p/$rel"
                    echo "LOCAL_MODULE_CLASS := APPS"
                    echo "LOCAL_MODULE_SUFFIX := .apk"
                    echo "LOCAL_CERTIFICATE := PRESIGNED"
                    echo "LOCAL_MODULE_TAGS := optional"
                    echo "LOCAL_DEX_PREOPT := false"
                    echo "LOCAL_MODULE_PATH := $out${dir:+/$dir}"
                    if [ "$dir" = "overlay" ]; then
                        echo "LOCAL_IS_RUNTIME_RESOURCE_OVERLAY := true"
                    fi
                    echo "include \$(BUILD_PREBUILT)"
                    echo ""
                } >> "$GAPPS/Android.mk"
                printf 'PRODUCT_PACKAGES += %s\n' "$mod" >> "$GAPPS/gapps.mk"
                ;;
            *)
                printf 'PRODUCT_COPY_FILES += $(GAPPS_DIR)/%s/%s:%s/%s\n' \
                    "$p" "$rel" "$dst" "$rel" >> "$GAPPS/gapps.mk"
                ;;
        esac
    done
done

files=$(grep -c '^PRODUCT_COPY_FILES' "$GAPPS/gapps.mk" || true)
mods=$(grep -c '^PRODUCT_PACKAGES' "$GAPPS/gapps.mk" || true)
size=$(du -sh --exclude=gapps.mk --exclude=Android.mk "$GAPPS" | cut -f1)
say "installing $files files and $mods prebuilt modules, $size"

# Two destinations must not collide with a platform file: a duplicate
# PRODUCT_COPY_FILES rule is a hard build error. A duplicate module name is a
# hard error too.
dupes=$(grep '^PRODUCT_COPY_FILES' "$GAPPS/gapps.mk" | grep -o ':[^:]*$' | sort | uniq -d || true)
if [ -n "$dupes" ]; then
    say "duplicate destinations inside the archive:"
    printf '%s\n' "$dupes"
    exit 1
fi

dupes=$(grep '^LOCAL_MODULE :=' "$GAPPS/Android.mk" | sort | uniq -d || true)
if [ -n "$dupes" ]; then
    say "duplicate module names inside the archive:"
    printf '%s\n' "$dupes"
    exit 1
fi

# Every module has to point at a file that is really in the payload. A wrong
# relative path surfaces much later, as a ninja "missing and no known rule to
# make it" error at the end of a long build.
missing=$(grep '^LOCAL_SRC_FILES :=' "$GAPPS/Android.mk" \
    | sed 's|^LOCAL_SRC_FILES := ||' \
    | while IFS= read -r s; do
        [ -f "$GAPPS/$s" ] || printf '%s\n' "$s"
    done)
if [ -n "$missing" ]; then
    say "Android.mk references files that are not in the payload:"
    printf '%s\n' "$missing"
    exit 1
fi

say "gapps.mk and Android.mk written"