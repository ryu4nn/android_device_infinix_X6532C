#!/usr/bin/env python3
"""Generate vintf/compatibility_matrix.device.xml from the stock vendor manifest.

The vendor partition's manifest is target-level 5 but declares HAL versions that
are newer than the AOSP level-5 framework matrix (radio@1.6, wifi@1.5, usb@1.3,
audio@7.0, drm@1.4, mtkradioex@3.0, lbs@1.0, ...). checkvintf rejects that pair:

    files are incompatible: The following instances are in the device manifest
    but not specified in framework compatibility matrix

Everything the vendor declares is copied into a framework matrix fragment with
optional="true", which means "permitted if present" without requiring it. That
is exactly the shape of a device compatibility matrix.

Usage:
    ./tools/gen-vintf-matrix.py <vendor-repo>/proprietary/vendor/etc/vintf

Writes vintf/compatibility_matrix.device.xml next to this script's parent.
"""

import os
import sys
import xml.etree.ElementTree as ET

# Attributes and children that a <hal> may carry inside a *matrix*. A manifest
# entry may also carry <transport> and <impl>, which the matrix schema rejects.
MATRIX_CHILDREN = ("name", "version", "interface", "fqname", "regex-instance")


def hal_entries(path):
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as exc:
        print(f"skip {path}: {exc}", file=sys.stderr)
        return []
    if root.tag not in ("manifest", "manifest-fragment"):
        return []
    return root.findall("hal")


def normalise(hal):
    """Return a matrix-ready <hal> element, or None if it carries nothing usable."""
    fmt = hal.get("format", "hidl")
    out = ET.Element("hal", {"format": fmt, "optional": "true"})
    for child in hal:
        if child.tag in MATRIX_CHILDREN:
            out.append(child)
    if out.find("name") is None:
        return None
    if out.find("version") is None and out.find("fqname") is None:
        return None
    return out


def key(hal):
    name = hal.findtext("name", "")
    version = hal.findtext("version", "")
    parts = [name, version]
    for iface in hal.findall("interface"):
        parts.append(iface.findtext("name", ""))
        for inst in iface.findall("instance"):
            parts.append(inst.text or "")
    for fq in hal.findall("fqname"):
        parts.append(fq.text or "")
    return "|".join(parts)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    vintf_dir = sys.argv[1]
    if not os.path.isdir(vintf_dir):
        sys.exit(f"not a directory: {vintf_dir}")

    sources = [os.path.join(vintf_dir, "manifest.xml")]
    sub = os.path.join(vintf_dir, "manifest")
    if os.path.isdir(sub):
        sources += [os.path.join(sub, f) for f in sorted(os.listdir(sub)) if f.endswith(".xml")]

    seen, entries = set(), []
    for path in sources:
        for hal in hal_entries(path):
            norm = normalise(hal)
            if norm is None:
                continue
            k = key(norm)
            if k in seen:
                continue
            seen.add(k)
            entries.append(norm)

    root = ET.Element("compatibility-matrix", {
        "version": "1.0",
        "type": "framework",
        "level": "5",
    })
    root.append(ET.Comment(
        " Generated by tools/gen-vintf-matrix.py from the stock vendor manifest. "
    ))
    for e in entries:
        root.append(e)

    ET.indent(root, space="    ")
    out_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "vintf", "compatibility_matrix.device.xml")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    ET.ElementTree(root).write(out_path, encoding="utf-8", xml_declaration=True)
    print(f"{len(entries)} HAL entries -> {out_path}")

    names = sorted({e.findtext("name") for e in entries})
    print(f"{len(names)} distinct HAL names")
    for n in names:
        print(f"  {n}")


if __name__ == "__main__":
    main()